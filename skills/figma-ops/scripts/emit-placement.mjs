#!/usr/bin/env node
// emit-placement.mjs — turn a plan into the exact `use_figma` script that places it.
//
// The last mile between plan-layout.mjs and the canvas was hand-typed every round:
// a loop of getNodeByIdAsync / appendChild / resize / x / y with fourteen IDs copied
// by eye. This generates that script verbatim from the plan, so IDs, sizes and
// z-order come from data. Paste stdout into use_figma's `code` (with figma-use loaded).
//
// Two scripts are emitted, because the backdrop's node ID is only known after it is
// created: `--phase backdrop` creates the backdrop frame and returns its ID;
// `--phase place --backdrop <id>` places every image (and captions, if any) into it.
//
// The vet gate lives here on purpose: this is the last step before pixels hit the
// canvas. Images whose plan entry carries `vetted: false` are refused (exit 10)
// unless --allow-unvetted is passed. "Looked at by a person" is a property of the
// data, not a memory of the conversation.
//
// Contract: stdout is the script (data), stderr diagnostics.
//   0 emitted · 2 usage · 3 bad input · 10 refused (unvetted images present)
//
// Plan shape: output of plan-layout.mjs --json, optionally with per-image
// `caption` (string) and `vetted` (bool) copied through from the board JSON, and
// `id` overwritten with the Figma node ID after upload (the slug is not a node ID).

import { readFileSync } from 'node:fs';

const HELP = `emit-placement.mjs — generate the use_figma script for a plan

Usage:
  node emit-placement.mjs --plan FILE --phase backdrop [--page NAME] [--name TEXT] [--fill HEX]
  node emit-placement.mjs --plan FILE --phase place --backdrop NODE_ID [options]

Options:
  --plan FILE          plan-layout.mjs --json output ("-" = stdin)
  --phase backdrop|place
  --page NAME          page to create/switch to        (default: "Moodboard — Plus")
  --name TEXT          backdrop frame name             (default: "Reference board")
  --fill HEX           backdrop fill                   (default: 002D3C)
  --backdrop ID        backdrop node ID (place phase)
  --stroke HEX         hairline stroke on images       (default: A6A6A6 at 0.45)
  --no-stroke          skip image strokes
  --captions           emit a caption node under each image that has one
  --caption-font FAM   caption font family             (default: "Roboto Mono")
  --allow-unvetted     place images flagged vetted:false (default: refuse, exit 10)
  -h, --help

EXAMPLES:
  node emit-placement.mjs --plan plan.json --phase backdrop --page "Moodboard — Plus"
  node emit-placement.mjs --plan plan.json --phase place --backdrop 45:2 --captions
`;

function usage(m) { process.stderr.write(`emit-placement: ${m}\n\n${HELP}`); process.exit(2); }
function bad(m) { process.stderr.write(`emit-placement: ${m}\n`); process.exit(3); }

const o = { plan: null, phase: null, page: 'Moodboard — Plus', name: 'Reference board', fill: '002D3C',
  backdrop: null, stroke: 'A6A6A6', noStroke: false, captions: false, captionFont: 'Roboto Mono', allowUnvetted: false };
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const a = argv[i], v = argv[i + 1];
  switch (a) {
    case '-h': case '--help': process.stdout.write(HELP); process.exit(0);
    case '--plan': o.plan = v; i++; break;
    case '--phase': o.phase = v; i++; break;
    case '--page': o.page = v; i++; break;
    case '--name': o.name = v; i++; break;
    case '--fill': o.fill = v; i++; break;
    case '--backdrop': o.backdrop = v; i++; break;
    case '--stroke': o.stroke = v; i++; break;
    case '--no-stroke': o.noStroke = true; break;
    case '--captions': o.captions = true; break;
    case '--caption-font': o.captionFont = v; i++; break;
    case '--allow-unvetted': o.allowUnvetted = true; break;
    default: usage(`unknown option ${a}`);
  }
}
if (!o.plan) usage('--plan is required');
if (!['backdrop', 'place'].includes(o.phase)) usage('--phase must be backdrop or place');
if (o.phase === 'place' && !/^\d+:\d+$/.test(o.backdrop || '')) usage('--phase place needs --backdrop <node id like 45:2>');

let plan;
try { plan = JSON.parse(o.plan === '-' ? readFileSync(0, 'utf8') : readFileSync(o.plan, 'utf8')); }
catch (e) { bad(`cannot read plan: ${e.message}`); }
if (!plan.canvas || !Array.isArray(plan.placements)) bad('plan needs canvas and placements[] (run plan-layout.mjs --json)');

const hex = h => { const m = /^#?([0-9a-f]{6})$/i.exec(h); if (!m) bad(`bad hex colour ${h}`); const n = parseInt(m[1], 16);
  return `{ r: ${((n >> 16) & 255) / 255}, g: ${((n >> 8) & 255) / 255}, b: ${(n & 255) / 255} }`; };
const js = s => JSON.stringify(String(s));

if (o.phase === 'backdrop') {
  process.stdout.write(`// generated by figma-ops/emit-placement.mjs — phase: backdrop
let page = figma.root.children.find(p => p.name === ${js(o.page)});
if (!page) { page = figma.createPage(); page.name = ${js(o.page)}; }
await figma.setCurrentPageAsync(page);
const bg = figma.createFrame();
bg.name = ${js(o.name)};
bg.resize(${plan.canvas.w}, ${plan.canvas.h});
bg.x = 0; bg.y = 0;
bg.fills = [{ type: 'SOLID', color: ${hex(o.fill)} }];
bg.clipsContent = false;
page.appendChild(bg);
return { pageId: page.id, backdropId: bg.id, canvas: [${plan.canvas.w}, ${plan.canvas.h}] };
`);
  process.exit(0);
}

// --- place phase -------------------------------------------------------------
const images = plan.placements.filter(p => p.id !== 'centre');
const notNodeId = images.filter(p => !/^\d+:\d+$/.test(String(p.id)));
if (notNodeId.length) bad(`these placements still carry a slug, not a Figma node ID — fill in ids after upload: ${notNodeId.map(p => p.id).join(', ')}`);
const unvetted = images.filter(p => p.vetted === false);
if (unvetted.length && !o.allowUnvetted) {
  process.stderr.write(`emit-placement: refusing ${unvetted.length} unvetted image(s): ${unvetted.map(p => p.name || p.id).join(', ')}\n  Look at each one, set vetted:true in the plan, or pass --allow-unvetted.\n`);
  process.exit(10);
}

// Placement order in the plan IS z-order: later entries sit on earlier ones.
const rows = images.map(p => `  [${js(p.id)}, ${p.x}, ${p.y}, ${p.w}, ${p.h}${o.captions && p.caption ? ', ' + js(p.caption) : ''}],`).join('\n');
const strokeLine = o.noStroke ? '' : `
  n.strokes = [{ type: 'SOLID', color: ${hex(o.stroke)}, opacity: 0.45 }];
  n.strokeWeight = 1; n.strokeAlign = 'OUTSIDE';`;
const captionBlock = o.captions ? `
const MONO = { family: ${js(o.captionFont)}, style: "Regular" };
await figma.loadFontAsync(MONO);
function caption(text, x, y) {
  const sq = figma.createRectangle(); bg.appendChild(sq);
  sq.resize(7, 7); sq.x = x; sq.y = y + 4;
  sq.fills = [{ type: 'SOLID', color: { r: 0.373, g: 0.698, b: 0.827 } }];
  const t = figma.createText(); bg.appendChild(t);
  t.fontName = MONO; t.characters = text; t.fontSize = 12;
  t.fills = [{ type: 'SOLID', color: ${hex(o.stroke)} }];
  t.letterSpacing = { unit: 'PERCENT', value: 8 };
  t.x = x + 17; t.y = y;
  return [sq.id, t.id];
}` : '';

process.stdout.write(`// generated by figma-ops/emit-placement.mjs — phase: place (${images.length} images)
const page = figma.root.children.find(p => p.name === ${js(o.page)});
await figma.setCurrentPageAsync(page);
const bg = await figma.getNodeByIdAsync(${js(o.backdrop)});
if (!bg) throw new Error("backdrop ${o.backdrop} not found on page ${o.page}");
${captionBlock}
// [id, x, y, w, h${o.captions ? ', caption' : ''}] — order is z-order
const PLAN = [
${rows}
];
const placed = [], captions = [], missing = [];
for (const [id, x, y, w, h, cap] of PLAN) {
  const n = await figma.getNodeByIdAsync(id);
  if (!n) { missing.push(id); continue; }
  bg.appendChild(n);
  n.rotation = 0;
  n.resize(w, h);
  n.x = x; n.y = y;${strokeLine}
  placed.push(id);${o.captions ? `
  if (cap) captions.push(...caption(cap, x, y + h + 14));` : ''}
}
return { placed, captions, missing, mutatedNodeIds: placed.concat(captions) };
`);
